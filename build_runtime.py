"""Build the transparent app-local localization DLL with MSVC x86."""
from pathlib import Path
import argparse,json,os,re,subprocess

ROOT=Path(__file__).resolve().parent

def cwide(s):
    return 'L'+json.dumps(s,ensure_ascii=True)

def generate():
    english=json.loads((ROOT/'data/english-strings.json').read_text(encoding='utf-8'))
    previous=json.loads((ROOT/'data/previous-translations.json').read_text(encoding='utf-8'))
    translated=json.loads((ROOT/'translations.json').read_text(encoding='utf-8'))
    pattern=re.compile(r'%(?:[-+ #0]*\d*(?:\.\d+)?[hlL]*[diuoxXfFeEgGcs%])')
    lines=['// Generated by build_runtime.py; do not edit.',
           'struct Translation {unsigned id;const wchar_t *english,*previous,*chinese;const char* encoded;};',
           'static const Translation translations[]={']
    for key,zh in translated.items():
        # Intro/credits/attribution are outside this review's translation scope.
        if 1000 <= int(key) <= 1361 or int(key) in (175,381):continue
        en=english[key]
        if pattern.findall(en)!=pattern.findall(zh):raise ValueError('Placeholder mismatch '+key)
        encoded=zh.encode('gbk')
        escaped='"'+''.join('\\x%02x'%v for v in encoded)+'"'
        lines.append('{%s,%s,%s,%s,%s},'%(key,cwide(en),cwide(previous.get(key,en)),cwide(zh),escaped))
    lines+=['};','static const Translation startupTranslations[]={']
    executable=json.loads((ROOT/'data/exe-text.json').read_text(encoding='utf-8'))
    for item in executable['resources']:
        en,zh=item['english'],item['chinese']
        if pattern.findall(en)!=pattern.findall(zh):raise ValueError('Startup placeholder mismatch')
        escaped='"'+''.join('\\x%02x'%v for v in zh.encode('gbk'))+'"'
        lines.append('{%d,%s,%s,%s,%s},'%(item['id'],cwide(en),cwide(zh),cwide(zh),escaped))
    lines+=['};','struct Literal {const char *english,*chinese;};','static const Literal executableLiterals[]={']
    for item in executable['literals']:
        en,zh=item['english'],item['chinese']
        if en in ('On','Off'):continue # Already translated at display time.
        if len(zh.encode('gbk'))>len(en.encode('ascii')):raise ValueError('Literal exceeds original buffer')
        if pattern.findall(en)!=pattern.findall(zh):raise ValueError('Literal placeholder mismatch')
        escaped='"'+''.join('\\x%02x'%v for v in zh.encode('gbk'))+'"'
        lines.append('{%s,%s},'%(json.dumps(en),escaped))
    lines+=['};','struct Pattern {const unsigned char *bytes,*mask;size_t size,call,count;};']
    patterns=json.loads((ROOT/'compat_patterns.json').read_text())
    for i,p in enumerate(patterns):
        tokens=p['pattern'].split()
        lines.append('static const unsigned char p%d[]={%s};'%(i,','.join('0' if t=='??' else '0x'+t for t in tokens)))
        lines.append('static const unsigned char m%d[]={%s};'%(i,','.join('0' if t=='??' else '1' for t in tokens)))
    lines.append('static const Pattern patterns[]={')
    for i,p in enumerate(patterns):lines.append('{p%d,m%d,sizeof(p%d),%d,%d},'%(i,i,i,p['call_offset'],p['count']))
    lines.append('};')
    lines.append('struct LayoutSite {const char* name;unsigned rva;size_t returnOffset;const unsigned char *bytes,*mask;size_t size;};')
    sites=json.loads((ROOT/'data/layout-sites.json').read_text(encoding='utf-8'))
    for i,p in enumerate(sites):
        tokens=p['pattern'].split()
        lines.append('static const unsigned char l%d[]={%s};'%(i,','.join('0' if t=='??' else '0x'+t for t in tokens)))
        lines.append('static const unsigned char lm%d[]={%s};'%(i,','.join('0' if t=='??' else '1' for t in tokens)))
    lines.append('static const LayoutSite layoutSites[]={')
    for i,p in enumerate(sites):lines.append('{"%s",%d,%d,l%d,lm%d,sizeof(l%d)},'%(p['name'],p['rva'],p['return_offset'],i,i,i))
    lines.append('};')
    lines.append('struct AlternateName {const char* original;const char* translated;};')
    lines.append('static const AlternateName alternateNames[]={')
    for p in json.loads((ROOT/'data/alternate-names.json').read_text(encoding='utf-8')):
        quote=lambda b:'"'+''.join('\\x%02x'%v for v in b)+'"'
        lines.append('{%s,%s},'%(quote(p['english'].encode('cp1252')),quote(p['chinese'].encode('gbk'))))
    lines.append('};')
    stage=ROOT/'build';stage.mkdir(exist_ok=True)
    (stage/'generated.hpp').write_text('\n'.join(lines)+'\n',encoding='utf-8')

def build():
    generate()
    vswhere=Path(os.environ.get('ProgramFiles(x86)',r'C:\Program Files (x86)'))/'Microsoft Visual Studio/Installer/vswhere.exe'
    installs=subprocess.check_output([str(vswhere),'-latest','-products','*','-requires','Microsoft.VisualStudio.Component.VC.Tools.x86.x64','-property','installationPath'],text=True).strip()
    vcvars=Path(installs)/'VC/Auxiliary/Build/vcvarsall.bat'
    if not vcvars.is_file():raise FileNotFoundError('需要Visual Studio C++ x86工具链')
    target=ROOT/'build'/'runtime';target.mkdir(exist_ok=True)
    batch=ROOT/'build'/'compile-runtime.cmd'
    command='cl /nologo /std:c++17 /O2 /MT /EHsc /W4 /utf-8 /LD '
    command+=' /I"'+str(ROOT/'build')+'" /Fo"'+str(target/'runtime.obj')+'" "'+str(ROOT/'zh_runtime.cpp')+'" "'+str(target/'runtime.res')+'" /link /Brepro /DYNAMICBASE /NXCOMPAT /INCREMENTAL:NO /DEF:"'+str(ROOT/'zh_runtime.def')+'" /OUT:"'+str(target/'XINPUT9_1_0.dll')+'" /IMPLIB:"'+str(target/'runtime.lib')+'" user32.lib gdi32.lib'
    resource='rc /nologo /fo "'+str(target/'runtime.res')+'" "'+str(ROOT/'runtime.rc')+'"'
    batch.write_text('@echo off\nchcp 65001 >nul\ncall "'+str(vcvars)+'" x86 >nul\nif errorlevel 1 exit /b 1\n'+resource+'\nif errorlevel 1 exit /b 1\n'+command+'\nexit /b %errorlevel%\n',encoding='utf-8')
    subprocess.run(['cmd.exe','/d','/c',str(batch)],cwd=ROOT,check=True)
    return target/'XINPUT9_1_0.dll'

if __name__=='__main__':
    print(build())
